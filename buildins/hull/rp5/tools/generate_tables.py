#!/usr/bin/env python3
"""Regenerate static WHATWG tables from the vendored parse5 reference."""
import ast
import html.entities
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
P5 = ROOT.parent / 'p5'

def rust_string(s):
    return '"' + ''.join('\\u{%x}' % ord(c) if ord(c) >= 127 or ord(c) < 32 else '\\' + c if c in '\\"' else c for c in s) + '"'

def strings(text):
    return [ast.literal_eval(match[0]) for match in re.finditer(r'''('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")''', text)]

# Python carries the same 2231 WHATWG named references as entities; every entry
# is independently checked against the vendored JavaScript decoder by verify_entities.mjs.
named = html.entities.html5
lines = ['// Generated by tools/generate_tables.py; verified against p5/entities 8.1.0.', 'pub static NAMED: &[(&str, &str)] = &[']
for name, value in sorted(named.items()):
    lines.append(f'    ({rust_string(name)}, {rust_string(value)}),')
lines.append('];')
(ROOT / 'src/entities_data.rs').write_text('\n'.join(lines) + '\n')
(ROOT / 'tools/entities_reference.json').write_text(json.dumps(named, ensure_ascii=False))

source = (P5 / 'src/common/doctype.ts').read_text()
quirks = strings(source.split('const QUIRKS_MODE_PUBLIC_ID_PREFIXES = [', 1)[1].split('];', 1)[0])
source = (P5 / 'src/common/foreign-content.ts').read_text()
lines = ['// Generated from vendored parse5 common/doctype.ts and foreign-content.ts.', 'pub const QUIRKS_PUBLIC_PREFIXES: &[&str] = &[']
lines.extend('    ' + rust_string(s) + ',' for s in quirks)
lines.append('];')
for js, rs in [('SVG_TAG_NAMES_ADJUSTMENT_MAP', 'SVG_TAG_ADJUSTMENTS'), ('SVG_ATTRS_ADJUSTMENT_MAP', 'SVG_ATTR_ADJUSTMENTS')]:
    block = source.split(js + ' = new Map(', 1)[1].split('].map', 1)[0]
    names = strings(block)
    lines.append(f'pub const {rs}: &[(&str, &str)] = &[')
    lines.extend(f'    ({rust_string(s.lower())}, {rust_string(s)}),' for s in names)
    lines.append('];')
(ROOT / 'src/parser_data.rs').write_text('\n'.join(lines) + '\n')
