#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import {
  copyFile,
  mkdir,
  readFile,
  writeFile,
} from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const EXPECTED_CORE = '1.2.6';
const EXPECTED_FRACTION = '5.2.1';
const EXPECTED_KABELSALAT = '0.4.1';

const toolDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(toolDir, '..');
const nodeModules = resolve(readArg('--node-modules') || join(toolDir, 'node_modules'));
const output = resolve(
  readArg('--output') ||
    join(repoRoot, 'apps', 'strudel_core', 'js', 'vendor', 'strudel-core.bundle.js'),
);
const allowVersionDrift = process.argv.includes('--allow-version-drift');

const corePackagePath = join(nodeModules, '@strudel', 'core', 'package.json');
const fractionPackagePath = join(nodeModules, 'fraction.js', 'package.json');
const kabelsalatPackagePath = join(nodeModules, '@kabelsalat', 'web', 'package.json');
const esbuildPath = join(nodeModules, 'esbuild', 'lib', 'main.js');

for (const required of [corePackagePath, fractionPackagePath, kabelsalatPackagePath, esbuildPath]) {
  if (!existsSync(required)) {
    fail(
      `missing ${required}\n` +
        `Install locally first:\n` +
        `  cd ${toolDir}\n` +
        `  npm install --no-save esbuild @strudel/core@${EXPECTED_CORE} fraction.js@${EXPECTED_FRACTION} @kabelsalat/web@${EXPECTED_KABELSALAT}`,
    );
  }
}

const corePackage = JSON.parse(await readFile(corePackagePath, 'utf8'));
const fractionPackage = JSON.parse(await readFile(fractionPackagePath, 'utf8'));
const kabelsalatPackage = JSON.parse(await readFile(kabelsalatPackagePath, 'utf8'));
if (!allowVersionDrift && corePackage.version !== EXPECTED_CORE) {
  fail(`expected @strudel/core ${EXPECTED_CORE}, found ${corePackage.version}`);
}
if (!allowVersionDrift && fractionPackage.version !== EXPECTED_FRACTION) {
  fail(`expected fraction.js ${EXPECTED_FRACTION}, found ${fractionPackage.version}`);
}
if (!allowVersionDrift && kabelsalatPackage.version !== EXPECTED_KABELSALAT) {
  fail(`expected @kabelsalat/web ${EXPECTED_KABELSALAT}, found ${kabelsalatPackage.version}`);
}

const { build } = await import(pathToFileURL(esbuildPath).href);
await mkdir(dirname(output), { recursive: true });
const buildResult = await build({
  entryPoints: [join(toolDir, 'strudel-entry.mjs')],
  outfile: output,
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  target: ['es2020'],
  treeShaking: true,
  minify: false,
  legalComments: 'eof',
  metafile: true,
  nodePaths: [nodeModules],
  banner: {
    js:
      `/* TRUEOS embedded @strudel/core pattern slice\n` +
      ` * @strudel/core ${corePackage.version}; fraction.js ${fractionPackage.version}\n` +
      ` * Generated by tools/vendor-strudel-core.mjs; retain upstream licenses.\n` +
      ` */`,
  },
  define: {
    'process.env.NODE_ENV': '"production"',
  },
});


const bundledInputs = Object.keys(buildResult.metafile.inputs).sort();
const forbiddenInputs = bundledInputs.filter(
  (path) =>
    path.includes('@kabelsalat/web') ||
    /(?:^|\/)@strudel\/core\/(?:ui|repl|cyclist)\.mjs$/.test(path),
);
if (forbiddenInputs.length !== 0) {
  fail(`browser/repl modules unexpectedly entered the pattern bundle:\n${forbiddenInputs.join('\n')}`);
}
await writeFile(
  join(dirname(output), 'vendor-inputs.json'),
  `${JSON.stringify({ inputs: bundledInputs }, null, 2)}\n`,
);

const licenseDir = join(dirname(output), 'licenses');
await mkdir(licenseDir, { recursive: true });
await copyIfPresent(
  join(nodeModules, '@strudel', 'core', 'LICENSE'),
  join(licenseDir, 'Strudel-AGPL-3.0-or-later.txt'),
);
await copyIfPresent(
  join(nodeModules, 'fraction.js', 'LICENSE'),
  join(licenseDir, 'fraction.js-MIT.txt'),
);

const bundle = await readFile(output);
const lock = {
  generatedAt: new Date().toISOString(),
  strategy: 'direct @strudel/core/pattern.mjs tree-shaken IIFE',
  core: {
    package: '@strudel/core',
    version: corePackage.version,
  },
  fraction: {
    package: 'fraction.js',
    version: fractionPackage.version,
  },
  kabelsalat: {
    package: '@kabelsalat/web',
    version: kabelsalatPackage.version,
    expectedInBundle: false,
    actualInBundle: bundledInputs.some((path) => path.includes('@kabelsalat/web')),
    note: 'Pinned because it is a published direct dependency; the direct pattern.mjs entry should not import it.',
  },
  bundledInputs: bundledInputs.length,
  sha256: createHash('sha256').update(bundle).digest('hex'),
  bytes: bundle.length,
};
await writeFile(join(dirname(output), 'vendor-lock.json'), `${JSON.stringify(lock, null, 2)}\n`);

process.env.TRUEOS_STRUDEL_BUNDLE = output;
await import(`${pathToFileURL(join(toolDir, 'smoke-generated.mjs')).href}?t=${Date.now()}`);
console.log(`wrote ${output}`);
console.log(`sha256 ${lock.sha256}`);

function readArg(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

async function copyIfPresent(source, destination) {
  if (existsSync(source)) await copyFile(source, destination);
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
