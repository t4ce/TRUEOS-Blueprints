#!/usr/bin/env python3
"""Bake Lico's UI4 shader, or verify the checked-in package without a compiler."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import sys


APP = Path(__file__).resolve().parents[1]
WORKSPACE = APP.parents[2]
KERNEL = WORKSPACE / "TRUEOS"
BAKERY = WORKSPACE / "tools/intel-gpu-bakery"
SOURCE = APP / "assets/visualizer/kernel.clcpp"
PACKAGE = APP / "assets/visualizer.stpkg"
NAME = "shadertoy_lico"
CONTRACT = KERNEL / f"crates/trueos-shader/gpgpu/kernels/artifacts/adls/cpp/{NAME}.contract.rs"
TRUST = KERNEL / "src/intel/gpgpu/artifacts/shadertoy_lico_package.rs"
MAGIC = b"STPKG01\0"
PARTS = struct.Struct("<6I")


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def load_parts(data):
    if data[:8] != MAGIC or len(data) < 8 + PARTS.size:
        raise SystemExit("Lico shader package header is invalid")
    lengths = PARTS.unpack_from(data, 8)
    offset = 8 + PARTS.size
    if min(lengths) == 0 or offset + sum(lengths) != len(data):
        raise SystemExit("Lico shader package lengths are invalid")
    parts = []
    for length in lengths:
        parts.append(data[offset:offset + length])
        offset += length
    return parts


def checked_metadata(parts):
    zebin, spirv, archive, source, provenance, contract = parts
    manifest = json.loads(provenance)
    source_record = manifest["source"]["inputs"]
    source_path = manifest["source"]["path"]
    expected_source = [{
        "path": source_path,
        "sha256": sha256(source),
        "size_bytes": len(source),
    }]
    if (
        source != SOURCE.read_bytes()
        or source_record != expected_source
        or json.loads(archive) != {source_path: source.decode()}
    ):
        raise SystemExit("Lico shader package source does not match its provenance")
    for name, field, payload in (
        ("elf", b"zebin_sha256", zebin),
        ("spirv", b"spv_sha256", spirv),
    ):
        record = manifest["artifact"][name]
        digest = hashlib.sha256(payload).digest()
        digest_field = re.search(rb"\b" + field + rb":\s*\[([^]]+)\]", contract)
        contract_digest = bytes.fromhex(
            b"".join(re.findall(rb"0x([0-9a-f]{2})", digest_field[1])).decode()
        ) if digest_field else None
        if (
            record["sha256"] != digest.hex()
            or record["size_bytes"] != len(payload)
            or contract_digest != digest
        ):
            raise SystemExit(f"Lico shader {name} does not match its provenance")
    trust = (
        "// Generated by apps/lico/tools/bake_visualizer.py. Payload remains Blueprint-owned.\n"
        "pub(crate) const SHADERTOY_LICO_PACKAGE: ShaderToyPackageContract = "
        "ShaderToyPackageContract {\n"
        f"    shader_id: 18, bin_bytes: {len(zebin)}, spv_bytes: {len(spirv)},\n"
        "};\n"
    )
    return contract, trust.encode()


def bake(toolchain):
    work = KERNEL / "bld/lico-visualizer-bake"
    subprocess.run([
        sys.executable, "-B", str(BAKERY / "bake.py"),
        "--source", str(SOURCE),
        "--artifact-name", NAME,
        "--expect-kernel", NAME,
        "--rust-symbol", f"{NAME}=SHADERTOY_LICO_ADLS_CPP_ABI_CONTRACT",
        "--profile", str(BAKERY / "profiles/adls-4680-r0c-shadertoy.json"),
        "--toolchain-lock", str(BAKERY / "toolchains/adls-shadertoy-relaxed.lock.json"),
        "--repro-check", "--build-root", str(work),
        "--clang", str(toolchain / "usr/lib/llvm-21/bin/clang"),
        "--llvm-spirv", str(toolchain / "usr/bin/llvm-spirv-21"),
        "--ocloc", str(toolchain / "usr/bin/ocloc-26.05.1"),
    ], check=True, cwd=KERNEL)
    output = work / "adls/cpp-native" / NAME / "run-a"
    zebin, spirv, provenance, contract = (
        (output / f"{NAME}.{suffix}").read_bytes()
        for suffix in ("bin", "spv", "manifest.json", "contract.rs")
    )
    source = SOURCE.read_bytes()
    source_path = json.loads(provenance)["source"]["path"]
    archive = (json.dumps({source_path: source.decode()}, sort_keys=True) + "\n").encode()
    return [zebin, spirv, archive, source, provenance, contract]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--toolchain-root", type=Path, default=KERNEL / "bld/spirit-shader-toolchain/root"
    )
    args = parser.parse_args()
    if args.check:
        parts = load_parts(PACKAGE.read_bytes())
        contract, trust = checked_metadata(parts)
        if CONTRACT.read_bytes() != contract or TRUST.read_bytes() != trust:
            raise SystemExit("Lico shader package does not match kernel metadata")
    else:
        parts = bake(args.toolchain_root.resolve())
        contract, trust = checked_metadata(parts)
        PACKAGE.write_bytes(MAGIC + PARTS.pack(*(len(part) for part in parts)) + b"".join(parts))
        CONTRACT.write_bytes(contract)
        TRUST.write_bytes(trust)
    print(f"Lico shader: {len(parts[0])} executable bytes, SHA-256 {sha256(parts[0])}")


if __name__ == "__main__":
    main()
